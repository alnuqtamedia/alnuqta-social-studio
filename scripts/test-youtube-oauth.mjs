import assert from 'node:assert/strict';
import {createYouTubeOAuth, YOUTUBE_SCOPES} from '../server/youtube-oauth.mjs';
const calls = [], queue = [];
const fetchImpl = async (url, options) => { calls.push({url, options}); const item = queue.shift(); return {ok:item.status === 200, status:item.status, json:async()=>item.body}; };
const config = {clientId:'test-id', clientSecret:'test-secret', redirectUri:'https://studio.example/api/youtube/callback', fetchImpl, now:()=>1000};
const adapter = createYouTubeOAuth(config);
const reply = (body, status=200) => queue.push({body, status});
reply({access_token:'access', refresh_token:'refresh', token_type:'Bearer', expires_in:3600, scope:YOUTUBE_SCOPES.join(' ')});
const credentials = await adapter.exchange({code:'test-code', redirectUri:config.redirectUri, verifier:'test-verifier'});
assert.equal(credentials.expiresAt, 3601000);
assert.equal(calls[0].options.body.get('code_verifier'), 'test-verifier');
assert.equal(calls[0].options.body.get('client_secret'), 'test-secret');
await assert.rejects(adapter.exchange({code:'code', redirectUri:'https://evil.example', verifier:'v'}));
reply({items:[{id:'channel', snippet:{title:'Alnuqta'}}]});
assert.deepEqual(await adapter.identify(credentials), {id:'channel', name:'Alnuqta', scopes:YOUTUBE_SCOPES});
reply({items:[]}); await assert.rejects(adapter.identify(credentials));
reply({access_token:'new', token_type:'Bearer', expires_in:3600});
assert.equal((await adapter.refresh(credentials)).refreshToken, 'refresh');
reply({access_token:'access', refresh_token:'refresh', token_type:'Bearer', expires_in:3600, scope:YOUTUBE_SCOPES[0]});
await assert.rejects(adapter.exchange({code:'code', redirectUri:config.redirectUri, verifier:'v'}));
reply({error_description:'sensitive-code'}, 400);
await assert.rejects(adapter.refresh(credentials), error => !error.message.includes('sensitive-code'));
reply({}); await adapter.revoke(credentials);
assert.equal(calls.at(-1).options.body.get('token'), 'refresh');
await assert.rejects(adapter.publish());
assert.equal(queue.length, 0);
console.log('YouTube OAuth adapter checks passed (mock HTTP; no live account linked).');
