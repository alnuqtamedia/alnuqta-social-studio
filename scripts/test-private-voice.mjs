import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const elements=Object.fromEntries(['private-voice-url','private-voice-token','private-voice-status','private-owner-option','ai-tts-voice'].map(id=>[id,{value:'',textContent:'',disabled:true}]));
const calls=[];
const ctx={window:{},URL,AbortSignal,document:{getElementById:id=>elements[id]},fetch:async(url,options)=>{calls.push({url,options});return {ok:true,json:async()=>url.endsWith('/status')?{available:true,voice:'private-owner'}:{voice:'private-owner',mimeType:'audio/wav',audio:'UklGRg=='}};}};
vm.runInNewContext(fs.readFileSync('public/private-voice.js','utf8'),ctx);
const voice=ctx.window.StudioPrivateVoice;
await assert.rejects(()=>voice.speech('خبر'),/اربط/);
elements['private-voice-url'].value='https://user:pass@example.com';
elements['private-voice-token'].value='x'.repeat(40);
await voice.connect();assert.equal(calls.length,0);
elements['private-voice-url'].value='http://192.168.1.2:7861';
await voice.connect();assert.equal(calls.length,0);
elements['private-voice-url'].value='http://127.0.0.1:7861';
await voice.connect();assert.equal(elements['ai-tts-voice'].value,'private-owner');
assert.equal(elements['private-voice-token'].value,'');
assert.equal(calls[0].options.headers.Authorization,'Bearer '+'x'.repeat(40));
const before=voice.cacheKey();await voice.speech('نص');assert.equal(JSON.parse(calls[1].options.body).text,'نص');
voice.disconnect();assert.notEqual(voice.cacheKey(),before);assert.equal(elements['private-owner-option'].disabled,true);
await assert.rejects(()=>voice.speech('خبر'),/اربط/);
console.log('Private voice connection, privacy and failure checks passed');
